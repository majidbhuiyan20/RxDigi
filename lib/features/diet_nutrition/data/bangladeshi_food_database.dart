  static List<BangladeshiFoodModel> searchFoods(String query) {
    final clean = query.trim().toLowerCase();
    if (clean.isEmpty) return allFoods;
    return allFoods.where((food) {
      return food.nameBn.toLowerCase().contains(clean) ||
          food.nameEn.toLowerCase().contains(clean) ||
          food.category.labelBn.toLowerCase().contains(clean) ||
          food.category.labelEn.toLowerCase().contains(clean);
    }).toList();
  }

  static List<BangladeshiFoodModel> filterByCategory(FoodCategory? category) {
    if (category == null) return allFoods;
    return allFoods.where((f) => f.category == category).toList();
  }

  static List<BangladeshiFoodModel> getDiabeticSafeFoods() {
    return allFoods.where((f) => f.diabeticRisk == DiabeticRisk.safe).toList();
  }
